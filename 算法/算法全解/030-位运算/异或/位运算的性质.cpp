//
//交换律：
//a & b = b & a
//a | b = b | a
//a ^ b = b ^ a
//
//结合律：
//(a & b) & c = a & (b & c)
//(a | b) | c = a | (b | c)
//(a ^ b) ^ c = a ^ (b ^ c)
//
//分配律：
//a & (b | c) = (a & b) | (a & c)
//a | (b & c) = (a | b) & (a | c)
//
//
//
//按位与（ & ）：
//a & 0 = 0（任何数与 0 相与都为 0）
//a & (-1) = a（任何数与全 1 相与都为自身， - 1 的二进制是全 1）
//a & a = a（自身与自身相与为自身）
//
//
//按位或（ | ）：
//a | 0 = a（任何数与 0 相或都为自身）
//a | (-1) = -1（任何数与全 1 相或都为全 1）
//a | a = a（自身与自身相或为自身）
//
//
//按位异或（ ^ ）：
//a ^ 0 = a（任何数与 0 异或都为自身）
//a ^ a = 0（自身与自身异或为 0）
//a ^ (-1) = ~a（任何数与全 1 异或等于取反，~是按位取反运算符）
//
//
//
//清除最低位的 1：a & (a - 1)
//例如：a = 6（110），a - 1 = 5（101），a & (a - 1) = 4（100）（清除了最低位的 1）
//
//
//获取最低位的 1：a & (-a)
//例如：a = 6（110）， - a = （补码）...11111010，a & (-a) = 2（10）（只保留最低位的 1）
//
//
//
//a + b = (a ^ b) + 2 * (a & b)
//（异或得到无进位加法结果，与运算得到进位位，左移 1 位相当于乘 2）
//
//
//(a & b) + (a | b) = a + b
//（即上一题用到的性质，可通过分析每一位的 0 / 1 组合证明）
//
//
//a ^ b = (a | b) - (a & b)
//（异或结果等于或运算结果减去与运算结果）
//
//
//
//若 a & b = 0，则 a | b = a + b（两数无重叠的 1，或运算等价于加法）
//若 a | b = a + b，则 a & b = 0（加法无进位，说明两数无重叠的 1）
//a ^ b ^ b = a（异或同一个数两次，结果为原数，可用于加密或交换变量）