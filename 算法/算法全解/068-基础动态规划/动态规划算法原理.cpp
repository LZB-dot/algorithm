//动态规划算法的基本思想是将一个复杂的问题分解为一系列相互关联的子问题，
//通过依次解决这些子问题，并利用子问题的解来构造原问题的解，
//同时在解决子问题的过程中避免重复计算，以提高算法效率，
//具体体现在以下几个方面：
//
//分解问题：将待求解的问题按照一定的方式划分为多个子问题，
//这些子问题与原问题具有相同的结构，但规模相对较小。
//例如在计算斐波那契数列的第n项时，
//将其分解为计算第n - 1项和第n - 2项这两个子问题，
//而计算第n - 1项和第n - 2项又可以继续分解为更小规模的子问题，
//直到最基础的第 0 项和第 1 项。
//
//求解子问题：采用自底向上或自顶向下的方式依次解决这些子问题。
//
//自底向上是从最基础、规模最小的子问题开始，逐步向上求解更大规模的子问题，
//如在计算斐波那契数列时，先计算出f(0)和f(1)，
//然后根据这两个结果计算f(2)，再依次计算f(3)、f(4)等；
//
//自顶向下则是从原问题开始，递归地将问题分解为子问题，
//直到遇到基础的子问题，然后逐步返回结果，
//如在计算斐波那契数列时，从f(n)开始，递归地计算f(n - 1)和f(n - 2)，
//直到f(0)和f(1)。
//
//记录与复用：在解决子问题的过程中，将已经解决的子问题的解记录下来。
//当再次需要求解同一个子问题时，直接从记录中获取结果，而不需要重新计算。
//这样就避免了大量的重复计算，提高了算法的效率。
//例如在计算斐波那契数列时，可以使用一个数组来存储已经计算出的斐波那契数，
//这样当需要再次使用某个数时，直接从数组中获取即可。
//
//利用最优子结构：如果原问题具有最优子结构性质，
//即原问题的最优解可以由子问题的最优解组合而成，
//那么动态规划算法会利用这一性质，
//通过求解子问题的最优解来构造原问题的最优解。
//例如在背包问题中，背包容量为W，有n个物品，
//背包问题的最优解可以通过考虑放入或不放入第n个物品，
//然后结合背包容量为W - w[n]（w[n]为第n个物品的重量）时的子问题的最优解来得到。